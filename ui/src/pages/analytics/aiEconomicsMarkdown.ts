import type { AiEconomics } from '../../api/analytics';

export const LAYER_LABELS: Record<string, string> = { L0_RULE: 'L0 rules', L1_SYSTEM_ONE: 'L1 Jev', L2_LLM: 'L2 LLM', L3_HUMAN: 'L3 human', DEFAULT: 'default' };
export const LAYER_COLORS: Record<string, string> = { L0_RULE: 'var(--l0)', L1_SYSTEM_ONE: 'var(--l1)', L2_LLM: 'var(--l2)', L3_HUMAN: 'var(--l3)', DEFAULT: 'var(--c6)' };
export const layerLabel = (l: string): string => LAYER_LABELS[l] ?? l;

const pct = (n: number, d = 1) => `${(n * 100).toFixed(d)}%`;
const usd = (n: number, d = 4) => `$${n.toFixed(d)}`;
const num = (n: number) => new Intl.NumberFormat('en-US').format(n);

/** Shareable Markdown summary of the AI economics report (what the "Copy as Markdown" button produces). */
export function aiEconomicsMarkdown(a: AiEconomics, tenant = 'tenant'): string {
  const lines: string[] = [];
  lines.push(`## AI economics — ${tenant} · ${a.range.from} → ${a.range.to} (${a.range.days} days)`, '');
  if (a.totalDecisions === 0) {
    lines.push('No live decisions were recorded in this range.', '');
  } else {
    lines.push('| Metric | Value |', '|---|---|',
      `| Decisions | ${num(a.totalDecisions)} |`,
      `| Automation rate | ${pct(a.automationRate)} (${num(a.actingDecisions)} acted autonomously) |`,
      `| Human decisions avoided (T1/T2) | ${num(a.humanDecisionsAvoided)} |`,
      `| Estimated analyst hours saved | ${a.estimatedAnalystHoursSaved.toFixed(1)} h (at ${a.minutesPerHumanDecision} min per decision, estimate) |`,
      `| Override rate | ${pct(a.overrideRate)} (${num(a.overrides)}) |`,
      `| Escalation rate | ${pct(a.escalationRate)} (${num(a.escalations)}) |`,
      `| AI spend | ${usd(a.totalAiCostUsd, 2)} · ${usd(a.costPer1kDecisionsUsd)} per 1k decisions · ${usd(a.costPerOrderUsd)} per order (${num(a.orders)} orders) |`, '');
    lines.push('### Decisions by layer', '', '| Layer | Count | Share | p50 ms | p95 ms |', '|---|---|---|---|---|');
    for (const l of a.byLayer) if (l.count > 0) lines.push(`| ${layerLabel(l.layer)} | ${num(l.count)} | ${pct(l.share)} | ${Math.round(l.latencyP50Ms)} | ${Math.round(l.latencyP95Ms)} |`);
    lines.push('');
    if (a.decisions.length) {
      lines.push('### Per decision', '', '| Decision | Tier | Volume | Automation | Avg confidence | Cost / 1k | p95 ms | Override |', '|---|---|---|---|---|---|---|---|');
      for (const d of a.decisions) lines.push(`| ${d.name} | ${d.tier ?? '—'} | ${num(d.volume)} | ${pct(d.automationRate)} | ${d.avgConfidence.toFixed(2)} | ${usd(d.costPer1kUsd)} | ${Math.round(d.latencyP95Ms)} | ${pct(d.overrideRate)} |`);
      lines.push('');
    }
  }
  lines.push('### Assumptions', '');
  for (const s of a.assumptions) lines.push(`- ${s}`);
  lines.push('', '_Generated by Intent OMS analytics._');
  return lines.join('\n');
}
